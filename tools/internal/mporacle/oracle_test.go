package mporacle

import "testing"

func TestRepr(t *testing.T) {
	for f, want := range map[float64]string{
		1: "1.0", 0.5: "0.5", 1e-5: "1e-05", 0.0001: "0.0001", 123456789: "123456789.0",
		1e16: "1e+16", 1.5e16: "1.5e+16", 9999999999999998: "9999999999999998.0", -2.5e-300: "-2.5e-300",
		0.0054152123482253955: "0.0054152123482253955", 184.6649652337873: "184.6649652337873",
		-1.0082281460997769e-13: "-1.0082281460997769e-13", 43867.0 / 244188: "0.17964437236883057",
	} {
		if got := Repr(f); got != want {
			t.Errorf("Repr(%v) = %s, want %s", f, got, want)
		}
	}
}

package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

// libmSources are the files of $GOROOT/src/math copied into internal/libm.
var libmSources = []string{
	"asin.go", "atan.go", "atan2.go", "atanh.go", "exp.go", "expm1.go",
	"hypot.go", "log.go", "log1p.go", "pow.go", "sin.go", "sincos.go",
	"sinh.go", "tan.go", "trig_reduce.go",
}

const genHeader = "// Code generated by go -C tools run ./fmalint --genlibm ../internal/libm; DO NOT EDIT.\n// Source: $GOROOT/src/math/%s, assembly dispatch removed, products rounded.\n\n"

// GenLibm writes the pure-Go bodies of the architecture-dependent math
// functions into outDir as package libm: each source file of goroot's
// src/math in libmSources with its package renamed, every
// `if haveArchF { return archF(...) }` dispatch removed, and every product
// rounded explicitly (Fix). outDir must already hold the package's
// hand-written glue (libm.go: the exact functions and constants the copies
// call) inside a module.
func GenLibm(goroot, outDir string) error {
	for _, name := range libmSources {
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, filepath.Join(goroot, "src", "math", name), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		f.Name.Name = "libm"
		ast.Inspect(f, func(n ast.Node) bool {
			b, ok := n.(*ast.BlockStmt)
			if !ok {
				return true
			}
			kept := b.List[:0]
			for _, s := range b.List {
				if is, ok := s.(*ast.IfStmt); ok {
					if id, ok := is.Cond.(*ast.Ident); ok && strings.HasPrefix(id.Name, "haveArch") {
						continue
					}
				}
				kept = append(kept, s)
			}
			b.List = kept
			return true
		})
		var buf bytes.Buffer
		fmt.Fprintf(&buf, genHeader, name)
		if err := format.Node(&buf, fset, f); err != nil {
			return err
		}
		src, err := format.Source(buf.Bytes())
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(outDir, name), src, 0o644); err != nil {
			return err
		}
	}
	for pass := 0; pass < 4; pass++ {
		fs, err := Lint(outDir, ".")
		if err != nil {
			return err
		}
		if len(fs) == 0 {
			return gofmtDir(outDir)
		}
		if _, err := Fix(fs, ""); err != nil {
			return err
		}
	}
	return fmt.Errorf("%s: products still open to fusion after 4 passes", outDir)
}

func gofmtDir(dir string) error {
	for _, name := range libmSources {
		p := filepath.Join(dir, name)
		src, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		out, err := format.Source(src)
		if err != nil {
			return err
		}
		if err := os.WriteFile(p, out, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// Command genkernel writes ../zz_kernel_tables.go, the tables of the
// float64 exp/log kernels (kernels.go), from mpmath at 400 bits:
//
//	go -C tools run ./genkernel
//
// expT[j] = 2^(j/128) as a double-double, j = 0..127.
// logT[j-192] = {invc, logc_hi, logc_lo}, j = 192..384: invc = 256/j
// rounded to float64, and -log(invc) — computed from that float64 value
// itself, so log(m) = -log(invc) + log1p(m*invc - 1) holds exactly —
// split as logc_hi, a multiple of 2^-42 (so k*ln2Hi42 + logc_hi is exact
// for |k| < 2^10), and logc_lo, the rest to 2^-96.
// ln2/128 split for the Cody-Waite reduction: expC1 has 35 significant
// bits (k*expC1 exact for |k| < 2^18), expC1 + expC2 = ln2/128 to about
// 2^-88 relative; ln2 split with ln2Hi42 a multiple of 2^-42 (42 bits,
// k*ln2Hi42 exact for |k| < 2^11).
//
// The arithmetic outside mpmath is big.Float at the same precision with
// correct rounding, as mpmath's mpf operations.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math/big"
	"os"

	"github.com/go-numerics/special/tools/internal/mporacle"
)

const prec = 400

func nf() *big.Float { return new(big.Float).SetPrec(prec) }

// truncBits rounds v to bits significant bits (ties to even), as
// float(nint(v*s)/s) with s = 2^(bits-1-floor(log2|v|)).
func truncBits(v *big.Float, bits int) float64 {
	e := v.MantExp(nil) - 1 // v = m 2^e, |m| in [1, 2)
	s := bits - 1 - e
	x := nf().SetMantExp(v, s)
	return mporacle.Float64(nf().SetMantExp(nint(x), -s))
}

// nint rounds to the nearest integer, ties to even (mpmath nint).
func nint(x *big.Float) *big.Float {
	i, _ := x.Int(nil) // truncation
	fi := nf().SetInt(i)
	d := nf().Sub(x, fi)
	half := big.NewFloat(0.5)
	switch d.Abs(d).Cmp(half) {
	case 1:
		if x.Sign() > 0 {
			i.Add(i, big.NewInt(1))
		} else {
			i.Sub(i, big.NewInt(1))
		}
	case 0:
		if i.Bit(0) == 1 {
			if x.Sign() > 0 {
				i.Add(i, big.NewInt(1))
			} else {
				i.Sub(i, big.NewInt(1))
			}
		}
	}
	return nf().SetInt(i)
}

func split(v *big.Float) (float64, float64) {
	hi := mporacle.Float64(v)
	return hi, mporacle.Float64(nf().Sub(v, nf().SetFloat64(hi)))
}

func main() {
	o, err := mporacle.Start()
	if err != nil {
		log.Fatal(err)
	}
	defer o.Close()
	r := mporacle.Repr
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("// Code generated by go -C tools run ./genkernel (mpmath %s, 400 bits); DO NOT EDIT.", mporacle.MpmathVersion)
	w("")
	w("package special")
	w("")
	ln2 := o.Eval(prec, "mp.log(2)", nil)
	c := nf().Quo(ln2, big.NewFloat(128))
	c1 := truncBits(c, 35)
	c2 := mporacle.Float64(nf().Sub(c, nf().SetFloat64(c1)))
	l1 := truncBits(ln2, 42)
	l2 := mporacle.Float64(nf().Sub(ln2, nf().SetFloat64(l1)))
	w("const (")
	w("\texpInvLn2N = %s // 128/ln2", r(mporacle.Float64(nf().Quo(big.NewFloat(128), ln2))))
	w("\texpC1      = %s // ln2/128, 35 bits", r(c1))
	w("\texpC2      = %s // ln2/128 - expC1", r(c2))
	w("\tln2Hi42    = %s // ln2, 42 bits", r(l1))
	w("\tln2Lo42    = %s // ln2 - ln2Hi42", r(l2))
	w(")")
	w("")
	w("// expT[j] = 2^(j/128) as {hi, lo}.")
	w("var expT = [128][2]float64{")
	var reqs []mporacle.Req
	for j := 0; j < 128; j++ {
		reqs = append(reqs, mporacle.Req{Expr: fmt.Sprintf("mpf(2) ** (mpf(%d) / 128)", j), Prec: prec})
	}
	vals, _, err := o.Batch(reqs)
	if err != nil {
		log.Fatal(err)
	}
	for _, v := range vals {
		h, l := split(v)
		w("\t{%s, %s},", r(h), r(l))
	}
	w("}")
	w("")
	w("// logT[j-192] = {invc = RN(256/j), -log(invc) to a multiple of 2^-42, the rest}, j = 192..384.")
	w("var logT = [193][3]float64{")
	reqs = reqs[:0]
	var invs []float64
	for j := 192; j <= 384; j++ {
		inv := mporacle.Float64(nf().Quo(big.NewFloat(256), big.NewFloat(float64(j))))
		invs = append(invs, inv)
		reqs = append(reqs, mporacle.Req{Expr: "-mp.log(x)", Prec: prec, Vars: map[string]*big.Float{"x": big.NewFloat(inv)}})
	}
	vals, _, err = o.Batch(reqs)
	if err != nil {
		log.Fatal(err)
	}
	two42 := new(big.Float).SetMantExp(big.NewFloat(1), 42)
	for i, v := range vals {
		hb := nint(nf().Mul(v, two42))
		h := mporacle.Float64(nf().Quo(hb, two42))
		l := mporacle.Float64(nf().Sub(v, nf().SetFloat64(h)))
		w("\t{%s, %s, %s},", r(invs[i]), r(h), r(l))
	}
	w("}")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("../zz_kernel_tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

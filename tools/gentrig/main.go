// Command gentrig writes ../cmplx/zz_trig_tables.go, the binary digits of
// 4/π used by the Payne–Hanek reduction of cmplx/trig.go, from mpmath:
//
//	go -C tools run ./gentrig
//
// fourOverPi[i] = floor(4/π · 2^(64 i)) mod 2^64, so that
// 4/π = Σ fourOverPi[i] · 2^(-64 i); 24 words (1472 fraction bits) cover
// the largest float64 exponent plus the 256-bit product window.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math/big"
	"os"

	"github.com/go-numerics/special/tools/internal/mporacle"
)

const words = 24

func main() {
	o, err := mporacle.Start()
	if err != nil {
		log.Fatal(err)
	}
	defer o.Close()
	v := o.Eval(64*words+256, "4/mp.pi", nil)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go -C tools run ./gentrig (mpmath %s); DO NOT EDIT.\n\npackage cmplx\n\n", mporacle.MpmathVersion)
	b.WriteString("// fourOverPi[i] = floor(4/π · 2^(64 i)) mod 2^64.\nvar fourOverPi = [...]uint64{\n")
	mod := new(big.Int).Lsh(big.NewInt(1), 64)
	for i := range words {
		s := new(big.Float).SetPrec(v.Prec()).SetMantExp(v, 64*i)
		n, _ := s.Int(nil) // truncation = floor (positive)
		n.Mod(n, mod)
		fmt.Fprintf(&b, "\t0x%016x,\n", n.Uint64())
	}
	b.WriteString("}\n\n// atanT[j] = atan(j/64) as {hi, lo}, j = 0..64.\nvar atanT = [65][2]float64{\n")
	var reqs []mporacle.Req
	for j := 0; j <= 64; j++ {
		reqs = append(reqs, mporacle.Req{Expr: fmt.Sprintf("mp.atan(mpf(%d)/64)", j), Prec: 300})
	}
	vals, _, err := o.Batch(reqs)
	if err != nil {
		log.Fatal(err)
	}
	for _, v := range vals {
		hi := mporacle.Float64(v)
		lo := mporacle.Float64(new(big.Float).SetPrec(400).Sub(v, new(big.Float).SetFloat64(hi)))
		fmt.Fprintf(&b, "\t{%s, %s},\n", mporacle.Repr(hi), mporacle.Repr(lo))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("../cmplx/zz_trig_tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

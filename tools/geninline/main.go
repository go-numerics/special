// Command geninline writes zz_inline.go: for each scalar function listed
// below, an array variant FTo whose loop body is the function's own body,
// with the hot helpers it calls expanded in place (recursively, from an
// allowlist), so that the element loop runs without a call per element.
//
//	go -C tools run ./geninline   (writes ../zz_inline.go)
//
// Under Go's register ABI every call spills the caller's live registers;
// for functions of a few ns that is a sizeable share of the cost, and the
// Go inliner does not inline functions this large. The expansion is
// mechanical and keeps the call semantics: every argument, result and
// stored value is rounded by an explicit float64 conversion, exactly as a
// call boundary rounds it, so the compiler cannot fuse a multiply-add
// across what was a call, and the results are bit-identical to the scalar
// functions (checked by TestInlinedLoopsBitIdentical).
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Functions given an array variant: name of the scalar function, name of
// the exported variant, and arity (1 or 2).
var targets = []struct {
	fn, out string
	arity   int
}{
	{"Gamma", "GammaTo", 1},
	{"LogGamma", "LogGammaTo", 1},
	{"Digamma", "DigammaTo", 1},
	{"Erf", "ErfTo", 1},
	{"Erfc", "ErfcTo", 1},
	{"Erfcx", "ErfcxTo", 1},
	{"ErfInv", "ErfInvTo", 1},
	{"ErfcInv", "ErfcInvTo", 1},
	{"Ndtr", "NdtrTo", 1},
	{"Ndtri", "NdtriTo", 1},
	{"LogNdtr", "LogNdtrTo", 1},
	{"Expit", "ExpitTo", 1},
	{"Logit", "LogitTo", 1},
	{"Log1pExp", "Log1pExpTo", 1},
	{"Zeta", "ZetaTo", 1},
	{"polygamma1", "TrigammaTo", 1},
	{"Beta", "BetaTo", 2},
	{"LogBeta", "LogBetaTo", 2},
	{"Xlogy", "XlogyTo", 2},
	{"HurwitzZeta", "HurwitzZetaTo", 2},
}

// Helpers expanded in place (functions, and methods as "Type.method").
var helpers = map[string]bool{
	"expHL": true, "logHL": true, "pow2": true,
	"erfcHL": true, "erfcxHL": true, "erfSmallHL": true, "ndtrZHL": true, "erfDeriv": true,
	"erfcInvHL": true, "erfInvSmallHL": true, "log1pHL": true,
	"gammaLarge": true, "gammaMid": true, "gamma1pHL": true, "gammaHL": true,
	"logGammaLargeHL": true, "logGammaLargeHL2": true,
	"digammaSmall": true, "digammaLarge": true,
	"zetaMidFast": true, "zetaTailFast": true, "trigamma": true, "trigammaAsym": true,
	"hurwitzFast": true, "powNegHL": true,
	"logBetaHL": true, "logBetaDirect": true, "logGammaDiffHL": true, "betaSmall": true,
	"estPiece.eval": true, "estPiece.evalLow": true, "estPiece.evalShort": true,
}

const maxDepth = 6

type decl struct {
	src  string // the declaration's source
	recv string // receiver type name for methods
}

var (
	decls = map[string]decl{}
	fset  = token.NewFileSet()
	seq   int
)

func main() {
	if err := os.Chdir(".."); err != nil { // the special package
		log.Fatal(err)
	}
	files, _ := filepath.Glob("*.go")
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") || f == "zz_inline.go" {
			continue
		}
		src, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		af, err := parser.ParseFile(fset, f, src, 0)
		if err != nil {
			log.Fatal(err)
		}
		for _, d := range af.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok {
				continue
			}
			key, recv := fd.Name.Name, ""
			if fd.Recv != nil {
				t := fd.Recv.List[0].Type
				if s, ok := t.(*ast.StarExpr); ok {
					t = s.X
				}
				recv = t.(*ast.Ident).Name
				key = recv + "." + key
			}
			var b bytes.Buffer
			printer.Fprint(&b, fset, fd)
			decls[key] = decl{b.String(), recv}
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by go -C tools run ./geninline; DO NOT EDIT.\n\npackage special\n\nimport (\n\t\"math\"\n\n\t\"github.com/go-numerics/special/internal/dd\"\n)\n\nvar _ = dd.F\n")
	for _, t := range targets {
		out.WriteString(genTarget(t.fn, t.out, t.arity))
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		os.WriteFile("zz_inline.go.broken", out.Bytes(), 0o644)
		log.Fatal(err)
	}
	if err := os.WriteFile("zz_inline.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// fresh returns a newly parsed copy of a declaration.
func fresh(key string) *ast.FuncDecl {
	d, ok := decls[key]
	if !ok {
		log.Fatalf("no declaration %s", key)
	}
	f, err := parser.ParseFile(token.NewFileSet(), "", "package p\n"+d.src, 0)
	if err != nil {
		log.Fatal(err)
	}
	return f.Decls[0].(*ast.FuncDecl)
}

func genTarget(fn, out string, arity int) string {
	fd := fresh(fn)
	// Every local of every expanded body carries a ζ suffix, so a free
	// identifier can only be package-level: no shadowing is possible.
	renameLocals(fd, "ζ0")
	params := fieldNames(fd.Type.Params)
	if len(params) != arity {
		log.Fatalf("%s: %d parameters", fn, len(params))
	}
	body := expand(fd.Body, []string{fn}, 0, func(res []ast.Expr) []ast.Stmt {
		if len(res) != 1 {
			log.Fatalf("%s: return of %d values", fn, len(res))
		}
		return parseStmts(fmt.Sprintf("ζdst[ζi] = float64(%s)\ncontinue ζloop", exprString(res[0])))
	})
	var b strings.Builder
	doc := fmt.Sprintf("Polygamma(1, x[i])")
	if fn != "polygamma1" {
		doc = fn + "(x[i])"
	}
	if arity == 1 {
		fmt.Fprintf(&b, "\n// %s sets dst[i] = %s for i < len(dst) (x at least as long),\n// bit-identical to the scalar function, in one loop with no call per\n// element: the loop of the nd functions.\nfunc %s(ζdst, ζx []float64) {\n\tζx = ζx[:len(ζdst)]\nζloop:\n\tfor ζi := range ζdst {\n\t\t%s := ζx[ζi]\n", out, doc, out, params[0])
	} else {
		fmt.Fprintf(&b, "\n// %s sets dst[i] = %s(a[i*sa], b[i*sb]) for i < len(dst) (a stride of 0\n// repeats a single value), bit-identical to the scalar function, in one\n// loop with no call per element: the loop of the nd functions.\nfunc %s(ζdst, ζa, ζb []float64, ζsa, ζsb int) {\nζloop:\n\tfor ζi := range ζdst {\n\t\t%s, %s := ζa[ζi*ζsa], ζb[ζi*ζsb]\n", out, fn, out, params[0], params[1])
	}
	b.WriteString(blockString(body))
	b.WriteString("\n\t}\n}\n")
	return b.String()
}

func fieldNames(fl *ast.FieldList) []string {
	var n []string
	if fl == nil {
		return n
	}
	for _, f := range fl.List {
		for _, id := range f.Names {
			n = append(n, id.Name)
		}
	}
	return n
}

func fieldTypes(fl *ast.FieldList) []string {
	var t []string
	if fl == nil {
		return t
	}
	for _, f := range fl.List {
		k := len(f.Names)
		if k == 0 {
			k = 1
		}
		for i := 0; i < k; i++ {
			t = append(t, exprString(f.Type))
		}
	}
	return t
}

func exprString(e ast.Node) string {
	var b bytes.Buffer
	printer.Fprint(&b, token.NewFileSet(), e)
	return b.String()
}

func blockString(b *ast.BlockStmt) string { return exprString(b) }

func parseStmts(src string) []ast.Stmt {
	f, err := parser.ParseFile(token.NewFileSet(), "", "package p\nfunc _() {\n"+src+"\n}", 0)
	if err != nil {
		log.Fatalf("%v\n%s", err, src)
	}
	return f.Decls[0].(*ast.FuncDecl).Body.List
}

// expand rewrites the statements of body: returns through onReturn, and
// calls of allowlisted helpers in `lhs := h(...)`, `lhs = h(...)` and
// `return h(...)` statements expanded in place.
func expand(body *ast.BlockStmt, stack []string, depth int, onReturn func([]ast.Expr) []ast.Stmt) *ast.BlockStmt {
	body.List = expandList(body.List, stack, depth, onReturn)
	return body
}

func expandList(list []ast.Stmt, stack []string, depth int, onReturn func([]ast.Expr) []ast.Stmt) []ast.Stmt {
	var out []ast.Stmt
	for _, s := range list {
		out = append(out, expandStmt(s, stack, depth, onReturn)...)
	}
	return out
}

func expandStmt(s ast.Stmt, stack []string, depth int, onReturn func([]ast.Expr) []ast.Stmt) []ast.Stmt {
	switch s := s.(type) {
	case *ast.ReturnStmt:
		if len(s.Results) == 1 {
			if key, call := helperCall(s.Results[0], stack, depth); key != "" {
				n := len(fieldTypes(fresh(key).Type.Results))
				var tmps []string
				for i := 0; i < n; i++ {
					seq++
					tmps = append(tmps, fmt.Sprintf("ζt%d", seq))
				}
				var lhs []ast.Expr
				for _, t := range tmps {
					lhs = append(lhs, ast.NewIdent(t))
				}
				stmts := inlineCall(key, call, lhs, true, stack, depth)
				var res []ast.Expr
				for _, t := range tmps {
					res = append(res, ast.NewIdent(t))
				}
				return append(stmts, onReturn(res)...)
			}
		}
		if len(s.Results) == 0 {
			return onReturn(nil)
		}
		return onReturn(s.Results)
	case *ast.AssignStmt:
		if len(s.Rhs) == 1 && (s.Tok == token.DEFINE || s.Tok == token.ASSIGN) {
			if key, call := helperCall(s.Rhs[0], stack, depth); key != "" {
				if n := len(fieldTypes(fresh(key).Type.Results)); n == len(s.Lhs) {
					return inlineCall(key, call, s.Lhs, s.Tok == token.DEFINE, stack, depth)
				}
			}
		}
	case *ast.BlockStmt:
		s.List = expandList(s.List, stack, depth, onReturn)
	case *ast.IfStmt:
		s.Body.List = expandList(s.Body.List, stack, depth, onReturn)
		if s.Else != nil {
			e := expandStmt(s.Else, stack, depth, onReturn)
			if len(e) == 1 {
				s.Else = e[0]
			} else {
				s.Else = &ast.BlockStmt{List: e}
			}
		}
	case *ast.ForStmt:
		s.Body.List = expandList(s.Body.List, stack, depth, onReturn)
	case *ast.RangeStmt:
		s.Body.List = expandList(s.Body.List, stack, depth, onReturn)
	case *ast.SwitchStmt:
		for _, c := range s.Body.List {
			cc := c.(*ast.CaseClause)
			cc.Body = expandList(cc.Body, stack, depth, onReturn)
		}
	case *ast.LabeledStmt:
		e := expandStmt(s.Stmt, stack, depth, onReturn)
		if len(e) == 1 {
			s.Stmt = e[0]
		} else {
			s.Stmt = &ast.BlockStmt{List: e}
		}
	}
	return []ast.Stmt{s}
}

// helperCall returns the allowlisted helper called by e, if any.
func helperCall(e ast.Expr, stack []string, depth int) (string, *ast.CallExpr) {
	call, ok := e.(*ast.CallExpr)
	if !ok || depth >= maxDepth {
		return "", nil
	}
	var key string
	switch f := call.Fun.(type) {
	case *ast.Ident:
		key = f.Name
	case *ast.SelectorExpr:
		for k, d := range decls {
			if d.recv != "" && strings.HasSuffix(k, "."+f.Sel.Name) && helpers[k] {
				key = k
			}
		}
	}
	if !helpers[key] {
		return "", nil
	}
	for _, s := range stack {
		if s == key {
			return "", nil
		}
	}
	return key, call
}

// inlineCall expands lhs (:)= key(call args) into statements.
func inlineCall(key string, call *ast.CallExpr, lhs []ast.Expr, define bool, stack []string, depth int) []ast.Stmt {
	seq++
	k := seq
	fd := fresh(key)
	suffix := fmt.Sprintf("ζ%d", k)
	renameLocals(fd, suffix)
	label := fmt.Sprintf("ζL%d", k)
	rtypes := fieldTypes(fd.Type.Results)
	rnames := fieldNames(fd.Type.Results)
	var tmps []string
	for i := range rtypes {
		tmps = append(tmps, fmt.Sprintf("ζr%d_%d", k, i))
	}
	var src strings.Builder
	for i, t := range tmps {
		fmt.Fprintf(&src, "var %s %s\n", t, rtypes[i])
	}
	src.WriteString("{\n")
	// receiver and parameters, rounded as at a call boundary
	args := call.Args
	if fd.Recv != nil {
		sel := call.Fun.(*ast.SelectorExpr)
		r := fd.Recv.List[0]
		recv := exprString(sel.X)
		if _, ok := r.Type.(*ast.StarExpr); ok {
			if _, isIdx := sel.X.(*ast.IndexExpr); isIdx {
				recv = "&" + recv
			}
		}
		fmt.Fprintf(&src, "%s := %s\n", r.Names[0].Name, recv)
	}
	pnames := fieldNames(fd.Type.Params)
	ptypes := fieldTypes(fd.Type.Params)
	if len(args) != len(pnames) {
		log.Fatalf("%s: %d args for %d params", key, len(args), len(pnames))
	}
	for i, p := range pnames {
		a := exprString(args[i])
		if ptypes[i] == "float64" || ptypes[i] == "int" {
			a = ptypes[i] + "(" + a + ")"
		}
		fmt.Fprintf(&src, "%s := %s\n", p, a)
	}
	for i, n := range rnames {
		fmt.Fprintf(&src, "var %s %s\n_ = %s\n", n, rtypes[i], n)
	}
	src.WriteString("ζBODY()\n}\n")
	fmt.Fprintf(&src, "%s:\n", label)
	if len(lhs) > 0 {
		var ls, rs []string
		for i, l := range lhs {
			ls = append(ls, exprString(l))
			rs = append(rs, tmps[i])
		}
		op := "="
		if define {
			op = ":="
		}
		fmt.Fprintf(&src, "%s %s %s\n", strings.Join(ls, ", "), op, strings.Join(rs, ", "))
	} else {
		src.WriteString(";\n")
	}
	stmts := parseStmts(src.String())
	body := expand(fd.Body, append(stack, key), depth+1, func(res []ast.Expr) []ast.Stmt {
		if res == nil {
			res = nil
			for _, n := range rnames {
				res = append(res, ast.NewIdent(n))
			}
		}
		if len(res) != len(tmps) {
			log.Fatalf("%s: return of %d values for %d results", key, len(res), len(tmps))
		}
		var b strings.Builder
		for i, r := range res {
			conv := exprString(r)
			if rtypes[i] == "float64" || rtypes[i] == "int" {
				conv = rtypes[i] + "(" + conv + ")"
			}
			fmt.Fprintf(&b, "%s = %s\n", tmps[i], conv)
		}
		fmt.Fprintf(&b, "goto %s\n", label)
		return parseStmts(b.String())
	})
	// splice the body in place of the ζBODY() placeholder
	for _, s := range stmts {
		blk, ok := s.(*ast.BlockStmt)
		if !ok {
			continue
		}
		var nl []ast.Stmt
		for _, t := range blk.List {
			if es, ok := t.(*ast.ExprStmt); ok {
				if c, ok := es.X.(*ast.CallExpr); ok {
					if id, ok := c.Fun.(*ast.Ident); ok && id.Name == "ζBODY" {
						nl = append(nl, body.List...)
						continue
					}
				}
			}
			nl = append(nl, t)
		}
		blk.List = nl
	}
	return stmts
}

// renameLocals appends suffix to every parameter, result, receiver and
// local variable of fd (identifiers declared inside it).
func renameLocals(fd *ast.FuncDecl, suffix string) {
	declared := map[string]bool{}
	add := func(fl *ast.FieldList) {
		for _, n := range fieldNames(fl) {
			declared[n] = true
		}
	}
	add(fd.Recv)
	add(fd.Type.Params)
	add(fd.Type.Results)
	ast.Inspect(fd.Body, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.AssignStmt:
			if n.Tok == token.DEFINE {
				for _, l := range n.Lhs {
					if id, ok := l.(*ast.Ident); ok && id.Name != "_" {
						declared[id.Name] = true
					}
				}
			}
		case *ast.ValueSpec:
			for _, id := range n.Names {
				declared[id.Name] = true
			}
		case *ast.RangeStmt:
			if n.Tok == token.DEFINE {
				for _, e := range []ast.Expr{n.Key, n.Value} {
					if id, ok := e.(*ast.Ident); ok && id.Name != "_" {
						declared[id.Name] = true
					}
				}
			}
		case *ast.LabeledStmt:
			declared[n.Label.Name] = true
		}
		return true
	})
	skip := map[*ast.Ident]bool{}
	ast.Inspect(fd, func(n ast.Node) bool {
		if s, ok := n.(*ast.SelectorExpr); ok {
			skip[s.Sel] = true
		}
		return true
	})
	skip[fd.Name] = true
	ast.Inspect(fd, func(n ast.Node) bool {
		if id, ok := n.(*ast.Ident); ok && !skip[id] && declared[id.Name] {
			id.Name += suffix
		}
		return true
	})
}


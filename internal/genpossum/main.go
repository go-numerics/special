//	go run ./internal/genpossum > possum4_gen_test.go
package main

import (
	"fmt"
	"strings"
)

const lane = `
		if actL {
			if i >= nm1L {
				actL, endL = false, i
			} else {
				s1h, e1 := dd.TwoSum(abhL, fi)
				s1l := e1 + ablL
				s2h, e2 := dd.TwoSum(a1hL, fi)
				s2l := e2 + a1lL
				th := float64(s1h * xhL)
				tl := math.FMA(s1h, xhL, -th) + (float64(s1h*xlL) + float64(s1l*xhL))
				r := 1 / s2h
				fh := float64(th * r)
				fl := float64((math.FMA(-fh, s2h, th) + tl - float64(fh*s2l)) * r)
				ph := float64(dhL * fh)
				dlL = math.FMA(dhL, fh, -ph) + (float64(dhL*fl) + float64(dlL*fh))
				dhL = ph
				var e float64
				shL, e = dd.TwoSum(shL, dhL)
				slL += e + dlL
				if i >= k0L && dhL <= 0x1p-16*shL {
					actL, endL = false, i+1
				}
			}
		}
`

func main() {
	var b strings.Builder
	b.WriteString("// Code generated by internal/genpossum; DO NOT EDIT.\n\npackage special\n\nimport (\n\t\"math\"\n\n\t\"github.com/go-numerics/special/dd\"\n)\n\n")
	b.WriteString("// psHead4 runs the head loop of ibetaPosSum for four independent elements\n// in lockstep, each lane leaving on its own convergence test.\nfunc psHead4(a, b, xh, xl *[4]float64, k0, n *[4]int) (out [4]psState) {\n")
	for l := 0; l < 4; l++ {
		s := fmt.Sprint(l)
		fmt.Fprintf(&b, "\tabh%s, abl%s := dd.TwoSum(a[%s], b[%s])\n", s, s, s, s)
		fmt.Fprintf(&b, "\ta1h%s, a1l%s := dd.TwoSum(a[%s], 1)\n", s, s, s)
		fmt.Fprintf(&b, "\txh%s, xl%s := xh[%s], xl[%s]\n", s, s, s, s)
		fmt.Fprintf(&b, "\tdh%s, dl%s, sh%s, sl%s := 1.0, 0.0, 1.0, 0.0\n", s, s, s, s)
		fmt.Fprintf(&b, "\tact%s, end%s, nm1%s, k0%s := true, 0, n[%s]-1, k0[%s]\n", s, s, s, s, s, s)
	}
	b.WriteString("\tfor i := 0; act0 || act1 || act2 || act3; i++ {\n\t\tfi := float64(i)\n")
	for l := 0; l < 4; l++ {
		s := fmt.Sprint(l)
		t := lane
		for _, v := range []string{"act", "end", "nm1", "k0", "abh", "abl", "a1h", "a1l", "xh", "xl", "dh", "dl", "sh", "sl"} {
			t = strings.ReplaceAll(t, v+"L", v+s)
		}
		b.WriteString(t)
	}
	b.WriteString("\t}\n")
	for l := 0; l < 4; l++ {
		s := fmt.Sprint(l)
		fmt.Fprintf(&b, "\tout[%s] = psState{dh%s, dl%s, sh%s, sl%s, end%s}\n", s, s, s, s, s, s)
	}
	b.WriteString("\treturn out\n}\n")
	fmt.Print(b.String())
}

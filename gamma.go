package special

import (
	"math"

	"github.com/go-numerics/special/internal/dd"
)

// Euler–Mascheroni constant.
const euler = 0.57721566490153286061

// log(sqrt(2*pi)) as a double-double.
var lnSqrt2Pi = dd.DD{Hi: 0.91893853320467278056, Lo: -3.8782941580672414e-17}

// log(pi) as a double-double.
var lnPi = dd.DD{Hi: 1.1447298858494002, Lo: 1.0265951162707826e-17}

// pi as a double-double.
var piDD = dd.DD{Hi: piHi, Lo: piLo}

// gammaMax is the largest x with Γ(x) finite in float64.
const gammaMax = 171.62437695630272

// factorials[n] = n! correctly rounded, n = 0..170.
var factorials [171]float64

func init() {
	// The products are formed in double-double and rounded once: every
	// partial product k! for k <= 170 is then within 2^-100 relative of the
	// exact value, so the rounding to float64 is correct except possibly at
	// a halfway case closer than that, which the gamma fixture's integer
	// region (checked against mpmath) would expose.
	p := dd.F(1)
	factorials[0] = 1
	for k := 1; k <= 170; k++ {
		p = dd.MulF(p, float64(k))
		factorials[k] = p.Float()
	}
}

// gamma1p returns Γ(1+t) for t in [-0.5, 1] as a double-double.
//
// Γ(1+t) = 1 + t(t-1)F(t), with F fitted by Chebyshev interpolation
// (zz_gamma1p_coeffs.go, generated by testdata/gen/fit.py from mpmath). The
// factor t(t-1) vanishes at both zeros of Γ(1+t)-1, so the result keeps full
// relative accuracy near t = 0 and t = 1 and the polynomial's own error is
// scaled down by |Γ(1+t)-1|/Γ(1+t) <= 0.43 (<= 0.15 on [0, 1]).
func gamma1p(t float64) dd.DD {
	return dd.AddF(gamma1pm1(t), 1)
}

// gamma1pm1 returns Γ(1+t) - 1 for t in [-0.5, 1] as a double-double.
func gamma1pm1(t float64) dd.DD {
	h, l := dd.TwoSum(t, -1)
	p := dd.MulF(dd.DD{Hi: h, Lo: l}, t)
	return dd.Mul(p, evalPiecesDD(gamma1pPieces[:], t))
}

// stirlingSeries returns the asymptotic correction
// log Γ(x) - [(x-1/2) log x - x + log sqrt(2π)] = Σ B_2k / (2k(2k-1) x^(2k-1))
// for x >= 10, summed to a truncation error below 2^-60 relative to log Γ(x)
// (DLMF 5.11.1).
func stirlingSeries(x float64) float64 {
	// B_2k/(2k(2k-1)), k = 1..9
	const (
		c1 = 1.0 / 12
		c2 = -1.0 / 360
		c3 = 1.0 / 1260
		c4 = -1.0 / 1680
		c5 = 1.0 / 1188
		c6 = -691.0 / 360360
		c7 = 1.0 / 156
		c8 = -3617.0 / 122400
		c9 = 43867.0 / 244188
	)
	if x > 1e10 {
		return c1 / x
	}
	z := 1 / (x * x)
	return (c1 + z*(c2+z*(c3+z*(c4+z*(c5+z*(c6+z*(c7+z*(c8+z*c9)))))))) / x
}

// logGammaStirling returns log Γ(x) for x >= 10 as a double-double.
func logGammaStirling(x float64) dd.DD {
	h, l := dd.TwoSum(x, -0.5)
	t := dd.Mul(dd.DD{Hi: h, Lo: l}, dd.Log(x))
	t = dd.AddF(t, -x)
	t = dd.Add(t, lnSqrt2Pi)
	return dd.AddF(t, stirlingSeries(x))
}

// Gamma returns the gamma function Γ(x) = ∫₀^∞ t^(x-1) e^(-t) dt, continued
// to negative x by Γ(x) = Γ(x+1)/x.
//
// Special values: Γ(+Inf) = +Inf; Γ(±0) = ±Inf; Γ(x) = NaN for x a negative
// integer, x = -Inf or NaN; Γ overflows to +Inf for x > 171.6243769563027
// and underflows to ±0 for x < -184.
//
// Algorithm: on t in [-0.5, 1], Γ(1+t) = 1 + t(t-1)F(t) with F a piecewise
// Chebyshev interpolant fitted to mpmath (testdata/gen/fit.py); other x in
// (0, 10) are reduced to it by the recurrence Γ(x+1) = xΓ(x), whose factors
// x-k are exact and whose product is carried in double-double; x >= 10 uses
// Stirling's series (DLMF 5.11.1) with (x-1/2)log x - x formed in
// double-double and exponentiated by dd.Exp; x < -34 uses the reflection
// formula Γ(x) = -π / (x sin(πx) Γ(-x)) with sin(πx) reduced exactly.
// Integers are a table of correctly rounded factorials. Measured error
// against mpmath: docs/accuracy.md.
func Gamma(x float64) float64 {
	switch {
	case math.IsNaN(x) || math.IsInf(x, -1):
		return math.NaN()
	case math.IsInf(x, 1):
		return x
	case x == 0:
		return math.Copysign(math.Inf(1), x)
	}
	if x == math.Trunc(x) {
		if x < 0 {
			return math.NaN()
		}
		if x <= 171 {
			return factorials[int(x)-1]
		}
		return math.Inf(1)
	}
	if x > 0 {
		return gammaPos(x).Float()
	}
	return gammaNeg(x)
}

// gammaPos returns Γ(x) as a double-double for non-integer 0 < x <= gammaMax
// and +Inf beyond. Below 10 the result is a double-double; from 10 the
// exponential limits it to about 0.8 ulp and the Lo part is zero.
func gammaPos(x float64) dd.DD {
	switch {
	case x > gammaMax:
		return dd.F(math.Inf(1))
	case x < 0x1p-56:
		return gammaTiny(x)
	case x < 1:
		// Γ(x) = Γ(1+x)/x
		return dd.DivF(gamma1p(x), x)
	case x <= 2:
		return gamma1p(x - 1) // x-1 is exact
	case x < 10:
		// Γ(x) = Γ(z) Π_{j=1}^{n} (x-j), z = x-n in (1, 2]; each x-j is
		// exact because j < x.
		n := math.Ceil(x - 2) // z = x - n in (1, 2]
		g := gamma1p(x - n - 1)
		for j := 1.0; j <= n; j++ {
			g = dd.MulF(g, x-j)
		}
		return g
	}
	return dd.F(dd.Exp(logGammaStirling(x)))
}

// gammaTiny returns Γ(x) for 0 < |x| < 2^-56: Γ(x) = 1/x - γ + O(x), the
// O(x) term being below 2^-112 relative; 1/x = q + r/x exactly with
// r = 1 - qx.
func gammaTiny(x float64) dd.DD {
	q := 1 / x
	if math.IsInf(q, 0) {
		return dd.F(q)
	}
	r := math.FMA(-q, x, 1)
	return dd.AddF(dd.DD{Hi: q, Lo: r / x}, -euler)
}

// gammaNeg returns Γ(x) for non-integer x < 0.
func gammaNeg(x float64) float64 {
	if x > -0x1p-56 {
		return gammaTiny(x).Float()
	}
	if x > -0.5 {
		// Γ(x) = Γ(1+x)/x with Γ(1+x) taken directly from the core
		// (x+1 itself would round).
		return dd.DivF(gamma1p(x), x).Float()
	}
	if x > -34 {
		// Γ(x) = Γ(1+t) / (t Π_{k=0}^{n-1} (x+k)), t = x+n in [0, 1).
		// Every x+k (k <= n) is exact: |x+k| <= |x| because |x| >= 0.5,
		// and x+k is a multiple of ulp(x). The denominator is therefore
		// formed exactly up to double-double rounding.
		n := math.Ceil(-x)
		t := x + n
		den := dd.F(t)
		for k := 0.0; k < n; k++ {
			den = dd.MulF(den, x+k)
		}
		return dd.Div(gamma1p(t), den).Float()
	}
	if x < -190 {
		// |Γ(x)| < 1e-350: underflows. Sign is that of (-1)^ceil(-x).
		return math.Copysign(0, gammaSignNeg(x))
	}
	// Reflection: Γ(x) = -π / (x sin(πx) Γ(-x)).
	s := sinPi(x)
	den := dd.MulFF(x, s)
	q := dd.Div(piDD, den) // π / (x sin πx)
	// Γ(x) = -q / Γ(-x) = -q exp(-log Γ(-x))
	lg := logGammaStirling(-x)
	lq := dd.Log(math.Abs(q.Hi))
	lq = dd.AddF(lq, q.Lo/q.Hi)
	v := dd.Exp(dd.Sub(lq, lg))
	if q.Hi > 0 {
		v = -v
	}
	return v
}

// gammaSignNeg returns the sign of Γ(x) for non-integer x < 0: (-1)^ceil(-x).
func gammaSignNeg(x float64) float64 {
	if math.Mod(math.Floor(x), 2) == 0 {
		return 1
	}
	return -1
}

// Euler–Mascheroni constant.
const euler = 0.57721566490153286061

// log(sqrt(2*pi)) as a double-double.
var lnSqrt2Pi = dd.DD{Hi: 0.91893853320467278056, Lo: -3.8782941580672414e-17}

// log(pi) as a double-double.
var lnPi = dd.DD{Hi: 1.1447298858494002, Lo: 1.0265951162707826e-17}

// gammaMax is the largest x with Γ(x) finite in float64.
const gammaMax = 171.62437695630272

// factorials[n] = n! correctly rounded, n = 0..170; factorialsDD[n] = n! as
// a double-double (exact to about 2^-100).
var (
	factorials   [171]float64
	factorialsDD [171]dd.DD
)

func init() {
	// The products are formed in double-double and rounded once: every
	// partial product k! for k <= 170 is then within 2^-100 relative of the
	// exact value, so the rounding to float64 is correct except possibly at
	// a halfway case closer than that, which the gamma fixture's integer
	// region (checked against mpmath) would expose.
	p := dd.F(1)
	factorials[0] = 1
	factorialsDD[0] = p
	for k := 1; k <= 170; k++ {
		p = dd.MulF(p, float64(k))
		factorials[k] = p.Float()
		factorialsDD[k] = p
	}
}

// gamma1p returns Γ(1+t) for t in [-0.5, 1] as a double-double.
//
// Γ(1+t) = 1 + t(t-1)F(t), with F fitted by Chebyshev interpolation
// (zz_gamma1p_coeffs.go, generated by testdata/gen/fit.py from mpmath). The
// factor t(t-1) vanishes at both zeros of Γ(1+t)-1, so the result keeps full
// relative accuracy near t = 0 and t = 1 and the polynomial's own error is
// scaled down by |Γ(1+t)-1|/Γ(1+t) <= 0.43 (<= 0.15 on [0, 1]).
func gamma1p(t float64) dd.DD {
	return dd.AddF(gamma1pm1(t), 1)
}

// gamma1pm1 returns Γ(1+t) - 1 for t in [-0.5, 1] as a double-double.
func gamma1pm1(t float64) dd.DD {
	h, l := dd.TwoSum(t, -1)
	p := dd.MulF(dd.DD{Hi: h, Lo: l}, t)
	return dd.Mul(p, evalPiecesDD(gamma1pPieces[:], t))
}

// stirlingSeries returns the asymptotic correction
// log Γ(x) - [(x-1/2) log x - x + log sqrt(2π)] = Σ B_2k / (2k(2k-1) x^(2k-1))
// for x >= 10, summed to a truncation error below 2^-60 relative to log Γ(x)
// (DLMF 5.11.1).
func stirlingSeries(x float64) float64 {
	// B_2k/(2k(2k-1)), k = 1..9
	const (
		c1 = 1.0 / 12
		c2 = -1.0 / 360
		c3 = 1.0 / 1260
		c4 = -1.0 / 1680
		c5 = 1.0 / 1188
		c6 = -691.0 / 360360
		c7 = 1.0 / 156
		c8 = -3617.0 / 122400
		c9 = 43867.0 / 244188
	)
	if x > 1e10 {
		return c1 / x
	}
	z := 1 / (x * x)
	return (c1 + z*(c2+z*(c3+z*(c4+z*(c5+z*(c6+z*(c7+z*(c8+z*c9)))))))) / x
}

// logGammaStirling returns log Γ(x) for x >= 10 as a double-double.
func logGammaStirling(x float64) dd.DD {
	h, l := dd.TwoSum(x, -0.5)
	t := dd.Mul(dd.DD{Hi: h, Lo: l}, dd.Log(x))
	t = dd.AddF(t, -x)
	t = dd.Add(t, lnSqrt2Pi)
	return dd.AddF(t, stirlingSeries(x))
}

// Gamma returns the gamma function Γ(x) = ∫₀^∞ t^(x-1) e^(-t) dt, continued
// to negative x by Γ(x) = Γ(x+1)/x.
//
// Special values: Γ(+Inf) = +Inf; Γ(±0) = ±Inf; Γ(x) = NaN for x a negative
// integer, x = -Inf or NaN; Γ overflows to +Inf for x > 171.6243769563027
// and underflows to ±0 for x < -184.
//
// Algorithm: on t in [-0.5, 1], Γ(1+t) = 1 + t(t-1)F(t) with F a piecewise
// Chebyshev interpolant fitted to mpmath (testdata/gen/fit.py); other x in
// (0, 10) are reduced to it by the recurrence Γ(x+1) = xΓ(x), whose factors
// x-k are exact and whose product is carried in double-double; x >= 10 uses
// Stirling's series (DLMF 5.11.1) with (x-1/2)log x - x formed in
// double-double and exponentiated by dd.Exp; x < -34 uses the reflection
// formula Γ(x) = -π / (x sin(πx) Γ(-x)) with sin(πx) reduced exactly.
// Integers are a table of correctly rounded factorials. Measured error
// against mpmath: docs/accuracy.md.
func Gamma(x float64) float64 {
	switch {
	case math.IsNaN(x) || math.IsInf(x, -1):
		return math.NaN()
	case math.IsInf(x, 1):
		return x
	case x == 0:
		return math.Copysign(math.Inf(1), x)
	}
	if x == math.Trunc(x) {
		if x < 0 {
			return math.NaN()
		}
		if x <= 171 {
			return factorials[int(x)-1]
		}
		return math.Inf(1)
	}
	if x > 0 {
		if x >= 10 {
			return gammaLarge(x)
		}
		if x >= 1 {
			h, l := gammaMid(x)
			return h + l
		}
		return gammaPos(x).Float()
	}
	return gammaNeg(x)
}

// Float64 fast paths (kernels.go). They evaluate the same formulas as
// gammaPos — Stirling's series above 10, the fitted Γ(1+t) and exact
// factors below — with the logarithm and the exponential from the float64
// kernels and the products formed as hi + lo; gammaPos remains for the
// callers that need a double-double and for 0 < x < 1.

// gamma1pEst holds the pieces of gamma1pPieces on [0, 1] (degrees <= 15).
var gamma1pEst = estPieces(gamma1pPieces[2:])

// stirlingHL returns Stirling's correction S(x) = log Γ(x) - [(x - 1/2)
// log x - x + log sqrt(2π)] for x >= 10 as hi + lo (DLMF 5.11.1, the
// coefficients and truncation of stirlingSeries): the leading term 1/(12x)
// with 1/x carried as hi + lo, the rest (below 1/(360x³)) by Estrin's
// scheme in z = 1/x², so that the result is accurate to about 2^-70
// absolute instead of the half ulp of S a float64 sum leaves. ix is 1/x
// rounded (the caller has it).
func stirlingHL(x, ix float64) (hi, lo float64) {
	const (
		c1   = 1.0 / 12
		c2   = -1.0 / 360
		c3   = 1.0 / 1260
		c4   = -1.0 / 1680
		c5   = 1.0 / 1188
		c6   = -691.0 / 360360
		c7   = 1.0 / 156
		c8   = -3617.0 / 122400
		c9   = 43867.0 / 244188
		c1lo = 4.625929269271485e-18 // 1/12 - c1
	)
	ixl := math.FMA(-ix, x, 1) * ix // 1/x = ix + ixl, ix = RN(1/x)
	z := ix * ix
	z2 := z * z
	z4 := z2 * z2
	a := math.FMA(math.FMA(c5, z, c4), z2, math.FMA(c3, z, c2))
	b := math.FMA(math.FMA(c9, z, c8), z2, math.FMA(c7, z, c6))
	tail := math.FMA(b, z4, a) * z * ix // Σ_{k>=2}
	hi = float64(ix * c1)
	return hi, math.FMA(ix, c1, -hi) + math.FMA(ixl, c1, math.FMA(ix, c1lo, tail))
}

// logGammaLargeHL returns log Γ(x) = (x - 1/2) log x - x + log sqrt(2π) +
// S(x) (DLMF 5.11.1) as hi + lo for x >= 10 (lo not normalised, below
// 2^-45 hi), from the log kernel (2^-68 absolute) with x - 1/2 = mh + ml
// exact, the product formed exactly up to its low-order terms and every
// sum of leading parts exact (Fast2Sum).
func logGammaLargeHL(x float64) (hi, lo float64) { return logGammaLargeHL2(x, 0) }

// logGammaLargeHL2 returns log Γ(x + xl) for x >= 10 and |xl| <= ulp(x)
// as logGammaLargeHL, the low part entering to first order through
// ψ(x) = log x - 1/(2x) + O(x^-2) (its relative error below 2^-8 on a
// term below 2^-50 of the result).
func logGammaLargeHL2(x, xl float64) (hi, lo float64) {
	// log x: logHL written out (x >= 10 is normal), as is stirlingHL
	// below — the calls would cost a fifth of LogGamma.
	ixb := math.Float64bits(x)
	tmp := ixb - 0x3fe8000000000000
	kf := float64(int64(tmp) >> 52)
	m := math.Float64frombits(ixb - uint64(int64(tmp)>>52)<<52)
	t := &logT[int(m*256+0.5)-192]
	invc := t[0]
	p := float64(m * invc) // float64(): not fused into r below
	pe := math.FMA(m, invc, -p)
	r := p - 1
	r2 := r * r
	q0 := math.FMA(r, 1.0/3, -0.5)
	q1 := math.FMA(r, 1.0/5, -0.25)
	q2 := math.FMA(r, 1.0/7, -1.0/6)
	q2 = math.FMA(r2, -1.0/8, q2)
	q1 = math.FMA(r2, q2, q1)
	q := r2 * math.FMA(r2, q1, q0)
	l0 := kf*ln2Hi42 + t[1]
	lh := l0 + r
	ll := (r - (lh - l0)) + (math.FMA(kf, ln2Lo42, t[2]) + (math.FMA(pe, -r, pe) + q))
	// (x - 1/2) log x
	ix := 1 / x
	mh := x - 0.5
	ml := (x - mh) - 0.5 // nonzero only above 2^52
	ph := float64(mh * lh)
	pl := math.FMA(mh, lh, -ph) + math.FMA(mh, ll, ml*lh)
	// S(x): stirlingHL
	const c1lo = 4.625929269271485e-18 // 1/12 - RN(1/12)
	c := &stirlingCoef
	ixl := math.FMA(-ix, x, 1) * ix
	z := ix * ix
	z2 := z * z
	z4 := z2 * z2
	sa := math.FMA(math.FMA(c[4], z, c[3]), z2, math.FMA(c[2], z, c[1]))
	sb := math.FMA(math.FMA(c[8], z, c[7]), z2, math.FMA(c[6], z, c[5]))
	tail := math.FMA(sb, z4, sa) * z * ix
	sh := float64(ix * c[0])
	sl := math.FMA(ix, c[0], -sh) + math.FMA(ixl, c[0], math.FMA(ix, c1lo, tail))
	v := ph - x // Fast2Sum: (x - 1/2) log x >= 2.2 x here
	vl := (ph - v) - x
	h1 := v + lnSqrt2Pi.Hi // Fast2Sum: v > 13
	e1 := (v - h1) + lnSqrt2Pi.Hi
	hi = h1 + sh // Fast2Sum: sh < 0.01
	e2 := (h1 - hi) + sh
	return hi, (e1 + e2) + (vl + pl + (lnSqrt2Pi.Lo + sl) + xl*math.FMA(-0.5, ix, lh))
}

// gammaLarge returns Γ(x) for 10 <= x (finite; +Inf above gammaMax):
// exp(log Γ(x)) with log Γ from logGammaLargeHL (absolute error about
// 2^-61 up to x = 171.6) normalised before the exponential kernel.
func gammaLarge(x float64) float64 {
	if x > gammaMax {
		return math.Inf(1)
	}
	h, l := logGammaLargeHL(x)
	hn := h + l
	eh, el, k := expHL(hn, l-(hn-h))
	return (eh + el) * pow2(k) // k <= 1023
}

// gamma1pHL returns Γ(1+t) as hi + lo for 0 <= t <= 1: 1 + t(t-1)F(t)
// with F from the fitted pieces and t(t-1) exact.
func gamma1pHL(t float64) (hi, lo float64) {
	fh, fl := gamma1pEst[min(int(t*4), 3)].eval(t)
	// u = t - 1 exactly (TwoSum), p = u t, g = p F
	uh := t - 1
	bb := uh - t
	ul := (t - (uh - bb)) + (-1 - bb)
	ph := float64(uh * t)
	pl := math.FMA(uh, t, -ph) + ul*t
	gh := float64(ph * fh)
	gl := math.FMA(ph, fh, -gh) + math.FMA(ph, fl, pl*fh)
	hi = 1 + gh // Fast2Sum: |Γ(1+t) - 1| < 0.12
	lo = ((1 - hi) + gh) + gl
	return hi, lo
}

// gammaMid returns Γ(x) as hi + lo for 1 <= x < 10: Γ(z) Π (x - j) with
// z = x - n in [1, 2] and every factor x - j exact, the product carried as
// hi + lo.
func gammaMid(x float64) (hi, lo float64) {
	n := math.Ceil(x - 2)
	if n <= 0 {
		return gamma1pHL(x - 1) // exact
	}
	hi, lo = gamma1pHL(x - n - 1)
	for j := 1.0; j <= n; j++ {
		f := x - j
		p := float64(hi * f)
		lo = math.FMA(hi, f, -p) + lo*f
		hi = p
	}
	return hi, lo
}

// gammaPos returns Γ(x) as a double-double for non-integer 0 < x <= gammaMax
// and +Inf beyond (relative error about 2^-56 from the fitted core below 10,
// about 2^-90 from Stirling's series and dd.ExpMant above).
func gammaPos(x float64) dd.DD {
	switch {
	case x > gammaMax:
		return dd.F(math.Inf(1))
	case x < 0x1p-56:
		return gammaTiny(x)
	case x < 1:
		// Γ(x) = Γ(1+x)/x
		return dd.DivF(gamma1p(x), x)
	case x <= 2:
		return gamma1p(x - 1) // x-1 is exact
	case x < 10:
		// Γ(x) = Γ(z) Π_{j=1}^{n} (x-j), z = x-n in (1, 2]; each x-j is
		// exact because j < x.
		n := math.Ceil(x - 2) // z = x - n in (1, 2]
		g := gamma1p(x - n - 1)
		for j := 1.0; j <= n; j++ {
			g = dd.MulF(g, x-j)
		}
		return g
	}
	m, k := dd.ExpMant(logGammaStirling(x))
	return dd.Ldexp(m, k)
}

// gammaTiny returns Γ(x) for 0 < |x| < 2^-56: Γ(x) = 1/x - γ + O(x), the
// O(x) term being below 2^-112 relative; 1/x = q + r/x exactly with
// r = 1 - qx.
func gammaTiny(x float64) dd.DD {
	q := 1 / x
	if math.IsInf(q, 0) {
		return dd.F(q)
	}
	r := math.FMA(-q, x, 1)
	return dd.AddF(dd.DD{Hi: q, Lo: r / x}, -euler)
}

// gammaNeg returns Γ(x) for non-integer x < 0.
func gammaNeg(x float64) float64 {
	if x > -0x1p-56 {
		return gammaTiny(x).Float()
	}
	if x > -0.5 {
		// Γ(x) = Γ(1+x)/x with Γ(1+x) taken directly from the core
		// (x+1 itself would round).
		return dd.DivF(gamma1p(x), x).Float()
	}
	if x > -34 {
		// Γ(x) = Γ(1+t) / (t Π_{k=0}^{n-1} (x+k)), t = x+n in [0, 1).
		// Every x+k (k <= n) is exact: |x+k| <= |x| because |x| >= 0.5,
		// and x+k is a multiple of ulp(x). The denominator is therefore
		// formed exactly up to double-double rounding.
		n := math.Ceil(-x)
		t := x + n
		den := dd.F(t)
		for k := 0.0; k < n; k++ {
			den = dd.MulF(den, x+k)
		}
		return dd.Div(gamma1p(t), den).Float()
	}
	if x < -190 {
		// |Γ(x)| < 1e-350: underflows. Sign is that of (-1)^ceil(-x).
		return math.Copysign(0, gammaSignNeg(x))
	}
	// Reflection: Γ(x) = -π / (x sin(πx) Γ(-x)).
	den := dd.MulF(sinPiDD(x), x)
	q := dd.Div(piDD, den) // π / (x sin πx)
	// Γ(x) = -q / Γ(-x) = -q exp(-log Γ(-x))
	lg := logGammaStirling(-x)
	lq := dd.Log(math.Abs(q.Hi))
	lq = dd.AddF(lq, q.Lo/q.Hi)
	v := dd.Exp(dd.Sub(lq, lg))
	if q.Hi > 0 {
		v = -v
	}
	return v
}

// gammaSignNeg returns the sign of Γ(x) for non-integer x < 0: (-1)^ceil(-x).
func gammaSignNeg(x float64) float64 {
	if math.Mod(math.Floor(x), 2) == 0 {
		return 1
	}
	return -1
}
